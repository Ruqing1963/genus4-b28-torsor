"""
octad_combinatorics.py -- the 63-point geometry of an octad (independent of the Legendre-interval repositories).

Abstract N-set E = {e_1, ..., e_N} in characteristic 2 with the single relation e_1 + ... + e_N = 0.
Model: an element of the span is a subset of E modulo complement, i.e. a vector of F_2^N / <(1,...,1)>.
For N = 8:
    duads   e_i + e_j                                     : C(8,2)   = 28
    tetrads e_i + e_j + e_k + e_l  (= its complement)     : C(8,4)/2 = 35
What the script verifies, exactly (no randomness, no external library except numpy for the group statistics):
  1. the 63 duads/tetrads together with 0 are closed under addition and form a 6-dimensional F_2-space V;
  2. <x,y> = |x cap y| mod 2 is a well-defined nondegenerate alternating form on V;
     Q(x) = |x|/2 mod 2 is a well-defined quadratic form with polar form <,>, of plus type (Arf 0);
     its 35 singular points are the tetrads, its 28 nonsingular points the duads;
  3. S_8 acts faithfully on V, preserves <,> and Q, has exactly the two orbits {duads}, {tetrads}; the group it
     generates inside GL(V) has order 40320; transpositions act as the transvections at the duads;
  4. the group generated by the transvections at all 63 points has order 1451520 = |Sp_6(F_2)|, is transitive on
     the 63 points, contains the image of S_8 with index 36, and S_8 is exactly the stabiliser of Q; of the 64
     quadratic forms with polar form <,>, 36 are of plus type and 28 of minus type;
  5. element orders of Sp_6(F_2) versus S_8 (order 9 occurs in Sp_6(F_2) but not in S_8), and the number of
     elements of Sp_6(F_2) that preserve at least one plus-type form, i.e. lie in some conjugate of S_8;
  6. the same construction for N = 6 (hexad): 15 duads, V = F_2^4, Q = |x|/2 is NOT well defined, S_6 = Sp_4(F_2);
     and the general identity  sum_{0<j<N/2, j even} C(N,j) + C(N,N/2)/2 = 2^{N-2} - 1  for N = 6, 8, 10, 12.
Usage: python octad_combinatorics.py          (about one to two minutes; the Sp_6(F_2) closure is done by hand)
"""
import itertools
import sys
import time
from collections import Counter
from math import comb

import numpy as np


# ----------------------------------------------------------------------------------------------------------------
# the model
# ----------------------------------------------------------------------------------------------------------------
class OctadModel:
    """Subsets of {0..N-1} modulo complement; even subsets form the space V = F_2^{N-2}."""

    def __init__(self, N):
        self.N = N
        self.FULL = (1 << N) - 1
        pts = set()
        for j in range(2, N // 2 + 1, 2):
            for S in itertools.combinations(range(N), j):
                pts.add(self.canon(sum(1 << i for i in S)))
        pts.discard(0)
        self.points = sorted(pts)
        self.by_weight = Counter(min(self.wt(p), N - self.wt(p)) for p in self.points)
        # closure and basis
        self.closed = all(self.canon(x ^ y) == 0 or self.canon(x ^ y) in pts for x in pts for y in pts)
        basis, span = [], {0}
        for p in self.points:
            if p not in span:
                basis.append(p)
                span = span | {self.canon(s ^ p) for s in span}
        self.basis, self.span, self.dim = basis, span, len(basis)
        # coordinates: element -> integer 0..2^dim-1
        self.coord = {}
        self.elem = [0] * (1 << self.dim)
        for mask in range(1 << self.dim):
            v = 0
            for i in range(self.dim):
                if mask >> i & 1:
                    v ^= basis[i]
            v = self.canon(v)
            self.coord[v] = mask
            self.elem[mask] = v
        n = 1 << self.dim
        # forms in coordinates
        self.IP = [[self.ip(self.elem[u], self.elem[v]) for v in range(n)] for u in range(n)]
        self.Q0 = [self.q(self.elem[u]) for u in range(n)]

    def canon(self, x):
        return min(x, x ^ self.FULL)

    @staticmethod
    def wt(x):
        return bin(x).count("1")

    def ip(self, x, y):
        return self.wt(x & y) & 1

    def q(self, x):
        return (self.wt(x) // 2) & 1

    # linear maps of V are stored as tuples of the images of the basis vectors (in coordinates)
    def apply(self, imgs, v):
        r = 0
        for i in range(self.dim):
            if v >> i & 1:
                r ^= imgs[i]
        return r

    def table(self, imgs):
        return [self.apply(imgs, v) for v in range(1 << self.dim)]

    def pack(self, imgs):
        k = 0
        for i, im in enumerate(imgs):
            k |= im << (self.dim * i)
        return k

    def unpack(self, key):
        m = (1 << self.dim) - 1
        return tuple((key >> (self.dim * i)) & m for i in range(self.dim))

    def perm_matrix(self, perm):
        """the linear map of V induced by the permutation perm of {0..N-1}"""
        imgs = []
        for b in self.basis:
            img = 0
            for i in range(self.N):
                if b >> i & 1:
                    img |= 1 << perm[i]
            imgs.append(self.coord[self.canon(img)])
        return tuple(imgs)

    def transvection(self, v):
        """x -> x + <x,v> v, v in coordinates"""
        return tuple((1 << i) ^ (v if self.IP[1 << i][v] else 0) for i in range(self.dim))

    def closure(self, gens):
        """all products of the generators (given as image tuples); returns the set of packed keys"""
        tabs = [self.table(g) for g in gens]
        ident = self.pack(tuple(1 << i for i in range(self.dim)))
        seen = {ident}
        frontier = [ident]
        d, m = self.dim, (1 << self.dim) - 1
        while frontier:
            new = []
            for key in frontier:
                imgs = [(key >> (d * i)) & m for i in range(d)]
                for T in tabs:
                    k2 = 0
                    for i in range(d):
                        k2 |= T[imgs[i]] << (d * i)
                    if k2 not in seen:
                        seen.add(k2)
                        new.append(k2)
            frontier = new
        return seen

    def perm_table(self, keys):
        """numpy: for the packed keys, the images of all 2^dim vectors; shape (len(keys), 2^dim)"""
        keys = np.asarray(sorted(keys), dtype=np.int64)
        d, m = self.dim, (1 << self.dim) - 1
        IM = np.stack([(keys >> (d * i)) & m for i in range(d)], axis=1).astype(np.uint8)
        n = 1 << d
        P = np.zeros((len(keys), n), dtype=np.uint8)
        for v in range(n):
            acc = np.zeros(len(keys), dtype=np.uint8)
            for i in range(d):
                if v >> i & 1:
                    acc ^= IM[:, i]
            P[:, v] = acc
        return P


def fmt_set(model, pts):
    return ", ".join("{" + "".join(str(i + 1) for i in range(model.N) if p >> i & 1) + "}" for p in pts)


