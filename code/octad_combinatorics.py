def octad_report():
    t0 = time.time()
    M = OctadModel(8)
    n = 1 << M.dim
    print("=" * 100)
    print("N = 8: the octad")
    print("=" * 100)
    print(f"points (even subsets of 8 modulo complement, nonzero): {len(M.points)}  by weight: {dict(M.by_weight)}")
    print(f"closed under addition: {M.closed};  dimension of the span: {M.dim};  |span| = {len(M.span)}")
    assert M.closed and M.dim == 6 and len(M.span) == 64 and len(M.points) == 63
    print("basis:", fmt_set(M, M.basis))

    # 2. forms
    well_ip = all(M.ip(x ^ M.FULL, y) == M.ip(x, y) for x in M.span for y in M.span)
    well_q = all(M.q(x ^ M.FULL) == M.q(x) for x in M.span)
    alt = all(M.ip(x, x) == 0 for x in M.span)
    nondeg = all(any(M.ip(x, y) for y in M.span) for x in M.span if x)
    polar = all(M.q(M.canon(x ^ y)) == (M.q(x) ^ M.q(y) ^ M.ip(x, y)) for x in M.span for y in M.span)
    sing = [p for p in M.points if M.q(p) == 0]
    nons = [p for p in M.points if M.q(p) == 1]
    print(f"<x,y> = |x cap y| mod 2 well defined: {well_ip}, alternating: {alt}, nondegenerate: {nondeg}")
    print(f"Q(x) = |x|/2 mod 2 well defined: {well_q}, polar form of Q is <,>: {polar}")
    print(f"singular points (Q=0): {len(sing)} = all tetrads: {all(min(M.wt(p), 8 - M.wt(p)) == 4 for p in sing)}")
    print(f"nonsingular points (Q=1): {len(nons)} = all duads: {all(min(M.wt(p), 8 - M.wt(p)) == 2 for p in nons)}")
    zeros = 1 + len(sing)
    print(f"zeros of Q including 0: {zeros} = 2^5 + 2^2 = 36  =>  Arf(Q) = 0, plus type: {zeros == 36}")
    assert well_ip and well_q and alt and nondeg and polar and len(sing) == 35 and len(nons) == 28

    # 3. S_8
    def perm_orbits(perms):
        seen, orbits = set(), []
        for p in M.points:
            if p in seen:
                continue
            orb, fr = {p}, [p]
            while fr:
                x = fr.pop()
                for pm in perms:
                    y = 0
                    for i in range(8):
                        if x >> i & 1:
                            y |= 1 << pm[i]
                    y = M.canon(y)
                    if y not in orb:
                        orb.add(y)
                        fr.append(y)
            seen |= orb
            orbits.append(sorted(orb))
        return orbits

    adj = [tuple(range(8)) for _ in range(7)]
    adj = []
    for i in range(7):
        p = list(range(8))
        p[i], p[i + 1] = p[i + 1], p[i]
        adj.append(tuple(p))
    orbs = perm_orbits(adj)
    print(f"S_8 orbits on the 63 points: sizes {[len(o) for o in orbs]}")
    gens8 = [M.perm_matrix(p) for p in adj]
    # transposition (i i+1) = transvection at the duad {i, i+1}
    tv_ok = all(M.perm_matrix(p) == M.transvection(M.coord[M.canon((1 << i) | (1 << (i + 1)))]) for i, p in enumerate(adj))
    print(f"transposition (i i+1) acts as the transvection at the duad {{i,i+1}}: {tv_ok}")
    S8 = M.closure(gens8)
    print(f"order of the group generated by S_8 on V: {len(S8)}  (8! = 40320, faithful: {len(S8) == 40320})")
    # generators preserve <,> and Q (hence the whole group does)
    pres = all(M.IP[M.apply(g, u)][M.apply(g, v)] == M.IP[u][v] for g in gens8 for u in range(n) for v in range(n))
    presq = all(M.Q0[M.apply(g, u)] == M.Q0[u] for g in gens8 for u in range(n))
    print(f"S_8 preserves <,>: {pres};  preserves Q: {presq}")
    assert len(S8) == 40320 and pres and presq and tv_ok

    # 4. Sp_6(2)
    tet = M.coord[0b00001111]  # a tetrad
    gens_sp = gens8 + [M.transvection(tet)]
    t1 = time.time()
    SP = M.closure(gens_sp)
    print(f"group generated by S_8 and one tetrad transvection: order {len(SP)}  "
          f"(|Sp_6(F_2)| = 2^9 (2^2-1)(2^4-1)(2^6-1) = {512 * 3 * 15 * 63}; {time.time() - t1:.1f} s)")
    assert len(SP) == 1451520
    # all 63 transvections lie in it, hence it is the full group generated by the transvections
    all_tv = all(M.pack(M.transvection(v)) in SP for v in range(1, n))
    print(f"contains all 63 transvections: {all_tv};  index of S_8: {len(SP) // len(S8)}")
    # transitivity on the points: orbit of one duad under the generators
    tabs = [M.table(g) for g in gens_sp]
    orb, fr = {1}, [1]
    while fr:
        x = fr.pop()
        for T in tabs:
            if T[x] not in orb:
                orb.add(T[x])
                fr.append(T[x])
    print(f"orbit of one point under Sp_6(F_2): {len(orb)} (transitive on the 63 points: {len(orb) == 63})")
    # the 64 quadratic forms Q_c = Q + <c,.>
    types = Counter()
    plus_forms = []
    for c in range(n):
        vals = [M.Q0[v] ^ M.IP[c][v] for v in range(n)]
        z = vals.count(0)
        types["plus (36 zeros)" if z == 36 else "minus (28 zeros)" if z == 28 else f"?? {z}"] += 1
        if z == 36:
            plus_forms.append(vals)
    print(f"quadratic forms with polar form <,>: {dict(types)}")
    # numpy statistics on the whole group
    t2 = time.time()
    P = M.perm_table(SP)
    Q0 = np.array(M.Q0, dtype=np.uint8)
    stab = int((Q0[P] == Q0[None, :]).all(axis=1).sum())
    print(f"elements of Sp_6(F_2) fixing Q: {stab} = |S_8|: {stab == 40320}")
    # orders
    ident = np.arange(n, dtype=np.uint8)[None, :]
    orders = np.zeros(len(P), dtype=np.int64)
    Pk = P.copy()
    for k in range(1, 40):
        done = (orders == 0) & (Pk == ident).all(axis=1)
        orders[done] = k
        if (orders > 0).all():
            break
        Pk = np.take_along_axis(P, Pk.astype(np.int64), axis=1)
    cnt = Counter(orders.tolist())
    print("element orders in Sp_6(F_2):", dict(sorted(cnt.items())))
    P8 = M.perm_table(S8)
    orders8 = np.zeros(len(P8), dtype=np.int64)
    Pk = P8.copy()
    for k in range(1, 40):
        done = (orders8 == 0) & (Pk == ident).all(axis=1)
        orders8[done] = k
        if (orders8 > 0).all():
            break
        Pk = np.take_along_axis(P8, Pk.astype(np.int64), axis=1)
    cnt8 = Counter(orders8.tolist())
    print("element orders in S_8:        ", dict(sorted(cnt8.items())))
    print("orders occurring in Sp_6(F_2) but not in S_8:", sorted(set(cnt) - set(cnt8)))
    # elements preserving at least one plus-type form
    F = np.array(plus_forms, dtype=np.uint8)  # (36, 64)
    keep = np.zeros(len(P), dtype=bool)
    step = 20000
    for s in range(0, len(P), step):
        Pc = P[s:s + step].astype(np.int64)
        G = F[:, Pc]  # (36, c, 64)
        keep[s:s + step] = (G == F[:, None, :]).all(axis=2).any(axis=0)
    nk = int(keep.sum())
    print(f"elements of Sp_6(F_2) preserving at least one plus-type form (= lying in a conjugate of S_8): {nk} "
          f"of {len(P)}  ({nk / len(P):.4f});  orders of the others: {dict(sorted(Counter(orders[~keep].tolist()).items()))}")
    # the minus-type forms: every element of Sp_6(F_2) preserves some quadratic form
    Fm = np.array([[M.Q0[v] ^ M.IP[c][v] for v in range(n)] for c in range(n)
                   if [M.Q0[v] ^ M.IP[c][v] for v in range(n)].count(0) == 28], dtype=np.uint8)
    keep_m = np.zeros(len(P), dtype=bool)
    for s in range(0, len(P), step):
        Pc = P[s:s + step].astype(np.int64)
        keep_m[s:s + step] = (Fm[:, Pc] == Fm[:, None, :]).all(axis=2).any(axis=0)
    stab_m = int((Fm[0][P] == Fm[0][None, :]).all(axis=1).sum())
    print(f"elements preserving at least one minus-type form: {int(keep_m.sum())};  preserving no quadratic form at all: "
          f"{int((~keep & ~keep_m).sum())};  stabiliser of one minus-type form: {stab_m} = |O_6^-(F_2)| = 51840: {stab_m == 51840}")
    print(f"all elements outside every conjugate of S_8 preserve a minus-type form: {bool((keep | keep_m).all())}")
    print(f"(group statistics {time.time() - t2:.1f} s)")
    # the coset: odd subsets modulo complement
    odd = {M.canon(sum(1 << i for i in S)) for j in (1, 3) for S in itertools.combinations(range(8), j)}
    print(f"the affine coset (odd subsets mod complement): {len(odd)} = 8 singletons + 56 triads "
          f"(as a model of T'^{{-1}}(1) = r_1 + K: 8 roots and 56 'triad totals')")
    print(f"total time {time.time() - t0:.1f} s")


def hexad_report():
    print("\n" + "=" * 100)
    print("N = 6: the hexad, for contrast")
    print("=" * 100)
    M = OctadModel(6)
    n = 1 << M.dim
    print(f"points: {len(M.points)} (duads; the tetrads are their complements), dimension {M.dim}, closed: {M.closed}")
    well_ip = all(M.ip(x ^ M.FULL, y) == M.ip(x, y) for x in M.span for y in M.span)
    well_q = all(M.q(x ^ M.FULL) == M.q(x) for x in M.span)
    print(f"<x,y> = |x cap y| mod 2 well defined: {well_ip};  Q = |x|/2 mod 2 well defined: {well_q} "
          f"(weight 2 and its complement weight 4 give 1 and 0)")
    adj = []
    for i in range(5):
        p = list(range(6))
        p[i], p[i + 1] = p[i + 1], p[i]
        adj.append(tuple(p))
    gens = [M.perm_matrix(p) for p in adj]
    S6 = M.closure(gens)
    tv = M.closure([M.transvection(v) for v in range(1, n)])
    print(f"|image of S_6| = {len(S6)};  |group generated by all 15 transvections| = {len(tv)} = |Sp_4(F_2)| = 720: "
          f"{len(tv) == 720 and len(S6) == 720}  (S_6 = Sp_4(F_2); no invariant quadratic form)")
    forms = Counter()
    for c in range(n):
        # quadratic forms with polar form <,>: Q_c(x) = sum over a symplectic basis ... use any one: build from a basis
        pass
    # count S_6-invariant quadratic forms with polar form <,>: a form is determined by its values on the basis
    inv = 0
    tabs = [M.table(g) for g in gens]
    for vals_on_basis in itertools.product((0, 1), repeat=M.dim):
        Qv = [0] * n
        for v in range(n):
            s = 0
            for i in range(M.dim):
                if v >> i & 1:
                    s ^= vals_on_basis[i]
                    for j in range(i + 1, M.dim):
                        if v >> j & 1:
                            s ^= M.IP[1 << i][1 << j]
            Qv[v] = s
        if all(Qv[T[v]] == Qv[v] for T in tabs for v in range(n)):
            inv += 1
    print(f"S_6-invariant quadratic forms with polar form <,>: {inv}")


def general_identity():
    print("\n" + "=" * 100)
    print("the counting identity for general N (N even): #(even subsets mod complement, nonzero) = 2^{N-2} - 1")
    print("=" * 100)
    for N in (6, 8, 10, 12):
        # even weights 0 < j < N/2 are counted once, weight N/2 (if even) is identified with its complement
        terms = [f"C({N},{j})={comb(N, j)}" for j in range(2, N // 2, 2)]
        total = sum(comb(N, j) for j in range(2, N // 2, 2))
        if (N // 2) % 2 == 0:
            terms.append(f"C({N},{N // 2})/2={comb(N, N // 2) // 2}")
            total += comb(N, N // 2) // 2
        print(f"  N={N:2d}: {' + '.join(terms)} = {total} = 2^{N - 2} - 1: {total == 2 ** (N - 2) - 1};"
              f"  Q = |x|/2 mod 2 well defined iff 4 | N: {N % 4 == 0}")
    print("  So 28 + 35 = 63 is the case N = 8 of a general identity; what is special at N = 8 is that Q is well defined")
    print("  (4 | N) and that S_8 = O_6^+(F_2) is the full orthogonal group (for N = 12, S_12 is a proper subgroup of O_10^+(F_2)).")


if __name__ == "__main__":
    octad_report()
    hexad_report()
    general_identity()
