r"""
ore_algebra_k6.py -- right division and right gcd in the twisted polynomial ring F_q{tau} (tau c = c^2 tau), and the
F_2[z]-module type of the q-Frobenius on the six-dimensional kernel K of

    P(tau) = tau^6 + l5^8 tau^5 + l3^8 tau^4 + tau^3 + l3^4 tau^2 + l5^2 tau + 1,
    L(x)   = P(tau)(x) = x^64 + l5^8 x^32 + l3^8 x^16 + x^8 + l3^4 x^4 + l5^2 x^2 + x      (l9 = 1),

computed without any field extension.

Facts used (all for separable additive polynomials, i.e. nonzero coefficient of tau^0):
  * composition L o M of additive polynomials corresponds to the product P * Q in F_q{tau};
  * ker P ⊆ ker Q over the algebraic closure iff P right-divides Q (Q = R * P);
  * the right ideal P F_q{tau} + Q F_q{tau} is principal, generated by the right gcd D = rgcd(P, Q),
    and ker D = ker P ∩ ker Q;
  * Frob_q = tau^k acts on K = ker P (P has coefficients in F_q); for g in F_2[z] the operator g(Frob_q) is
    the additive polynomial g(tau^k) (F_2 commutes with tau), so
        dim ker (g(Frob_q)|_K) = deg_tau rgcd(P, g(tau^k)),   rank (g(Frob_q)|_K) = 6 - deg_tau rgcd(P, g(tau^k));
  * the ranks of p(Frob_q)^j, p irreducible, j = 1..6, determine the elementary divisors of the F_2[z]-module K,
    i.e. the conjugacy class of Frob_q in GL_6(F_2); the same invariant is computed from matrices in genus_check.py
    for the 22 classes of S_8 on the octad space, so the two can be compared directly.

Self-test (python ore_algebra_k6.py): ring axioms and division identity on random elements; for (l5, l3) in F_2^2
and q = 2, 4, 8 the Ore computation is compared with the companion-matrix computation of genus_check.py
(Frob_q = C_ell^k), which must give the identical invariant; Frobenius orders and octad classification are printed.
"""
import random
import sys

from genus_check import (GF, canon_ranks, charpoly_from_invariant, companion, irreducibles, mat_pow, module_invariant,
                         pdeg, pmod, pmul, pstr, s8_modules)

IRR6 = irreducibles(6)
DIM = 6


class Ore:
    """F_q{tau}: elements are lists of coefficients in F_q, index = tau-degree; tau c = c^2 tau."""

    def __init__(self, F):
        self.F = F

    def frob(self, c, e):
        for _ in range(e):
            c = self.F.mul(c, c)
        return c

    @staticmethod
    def trim(a):
        while a and a[-1] == 0:
            a.pop()
        return a

    def mul(self, a, b):
        if not a or not b:
            return []
        out = [0] * (len(a) + len(b) - 1)
        for i, ai in enumerate(a):
            if ai:
                for j, bj in enumerate(b):
                    if bj:
                        out[i + j] ^= self.F.mul(ai, self.frob(bj, i))
        return self.trim(out)

    def add(self, a, b):
        out = [0] * max(len(a), len(b))
        for i, x in enumerate(a):
            out[i] ^= x
        for i, x in enumerate(b):
            out[i] ^= x
        return self.trim(out)

    def rdivmod(self, a, b):
        """a = r * b + s with deg s < deg b (right division by b)"""
        a = self.trim(list(a))
        b = self.trim(list(b))
        if not b:
            raise ZeroDivisionError
        n = len(b) - 1
        r = [0] * max(len(a) - n, 0)
        while a and len(a) - 1 >= n:
            m = len(a) - 1
            s = m - n
            c = self.F.mul(a[m], self.F.inv(self.frob(b[n], s)))  # leading term of c tau^s b is c b_n^{2^s} tau^m
            r[s] = c
            for i, bi in enumerate(b):
                if bi:
                    a[i + s] ^= self.F.mul(c, self.frob(bi, s))
            self.trim(a)
        return self.trim(r), a

    def rgcd(self, a, b):
        """monic right gcd: generator of the right ideal a F_q{tau} + b F_q{tau}; its kernel is ker a ∩ ker b"""
        a = self.trim(list(a))
        b = self.trim(list(b))
        while b:
            a, b = b, self.rdivmod(a, b)[1]
        c = self.F.inv(a[-1])
        return [self.F.mul(c, x) for x in a]

    def right_divides(self, p, q):
        return not self.rdivmod(q, p)[1]


def subst(g, k):
    """g(tau^k) for g in F_2[z] (integer bits): coefficients in {0,1}"""
    out = [0] * (k * pdeg(g) + 1)
    for i in range(pdeg(g) + 1):
        if g >> i & 1:
            out[k * i] = 1
    return out


def kernel_polynomial(F, l5, l3):
    return [1, F.pow(l5, 2), F.pow(l3, 4), 1, F.pow(l3, 8), F.pow(l5, 8), 1]


def frobenius_order(O, P, k, nmax=200):
    """smallest n with K ⊆ F_{q^n}: P right-divides tau^{kn} + 1"""
    for n in range(1, nmax + 1):
        if O.right_divides(P, subst((1 << n) | 1, k)):
            return n
    raise RuntimeError("order not found")


def frobenius_module(O, P, k, order=None):
    """module invariant of Frob_q = tau^k on ker P, same format as genus_check.module_invariant"""
    inv = []
    for p in IRR6:
        if order is not None and p != 0b10:
            # p can divide the characteristic polynomial only if its roots have order dividing `order`
            # (z^order = 1 on K): skip p unless p | z^order + 1
            if pmod((1 << order) | 1, p) != 0:
                continue
        ranks = []
        pj = 1
        for j in range(1, DIM + 1):
            pj = pmul(pj, p)
            d = len(O.rgcd(P, subst(pj, k))) - 1
            ranks.append(DIM - d)
            if len(ranks) > 1 and ranks[-1] == ranks[-2]:
                break
        if ranks[0] < DIM:
            inv.append((p, canon_ranks(ranks)))
    return tuple(inv)


def elementary_divisors(inv):
    """[(p, e), ...] from the rank sequences"""
    out = []
    for p, ranks in inv:
        r = [DIM] + list(ranks)
        # number of elementary divisors p^e with e >= j is (r[j-1] - r[j]) / deg p
        ge = [(r[j - 1] - r[j]) // pdeg(p) for j in range(1, len(r))]
        ge.append(0)
        for e in range(1, len(ge)):
            for _ in range(ge[e - 1] - ge[e]):
                out.append((p, e))
    return sorted(out)


def divisors_label(inv):
    ed = elementary_divisors(inv)
    parts = []
    for p, e in ed:
        parts.append(f"({pstr(p)})^{e}" if e > 1 else f"({pstr(p)})")
    return " ".join(parts)


def classify(inv, inv_to_classes):
    cls = inv_to_classes.get(inv)
    return "/".join(cls) if cls else None


# ----------------------------------------------------------------------------------------------------------------
def self_test():
    random.seed(1)
    print("ring tests in F_8{tau}:")
    F = GF(3)
    O = Ore(F)
    ok_assoc = ok_div = ok_gcd = True
    for _ in range(200):
        a = [random.randrange(8) for _ in range(random.randint(1, 5))]
        b = [random.randrange(8) for _ in range(random.randint(1, 5))]
        c = [random.randrange(8) for _ in range(random.randint(1, 5))]
        if O.mul(O.mul(a, b), c) != O.mul(a, O.mul(b, c)):
            ok_assoc = False
        if O.trim(list(b)):
            r, s = O.rdivmod(a, b)
            if O.add(O.mul(r, b), s) != O.trim(list(a)) or (s and len(s) >= len(O.trim(list(b)))):
                ok_div = False
            # rgcd(a*b, c*b) is right-divisible by b (b is a common right factor)
            d = O.rgcd(O.mul(a, b), O.mul(c, b))
            if O.rdivmod(d, b)[1]:
                ok_gcd = False
    print(f"  associativity: {ok_assoc};  a = r*b + s with deg s < deg b: {ok_div};  b | rgcd(a*b, c*b): {ok_gcd}")
    assert ok_assoc and ok_div and ok_gcd
    # tau c = c^2 tau
    c = 5
    print(f"  tau * c == c^2 * tau: {O.mul([0, 1], [c]) == O.mul([F.mul(c, c)], [0, 1])}")

    M, inv_to_classes, rows = s8_modules()
    print("\ncomparison with the companion-matrix computation (coefficients in F_2, q = 2, 4, 8):")
    all_ok = True
    for k in (1, 2, 3):
        F = GF(k)
        O = Ore(F)
        for l5 in (0, 1):
            for l3 in (0, 1):
                P = kernel_polynomial(F, l5, l3)
                n = frobenius_order(O, P, k)
                inv = frobenius_module(O, P, k, n)
                ell = (1 << 6) | (l5 << 5) | (l3 << 4) | (1 << 3) | (l3 << 2) | (l5 << 1) | 1
                inv_mat = module_invariant(mat_pow(companion(ell, 6), k, 6))
                same = inv == inv_mat
                all_ok &= same
                cls = classify(inv, inv_to_classes)
                print(f"  q={1 << k}: (l5,l3)=({l5},{l3})  order of Frob_q on K = {n:2d}  Ore == matrix: {same!s:5s}  "
                      f"char poly {pstr(charpoly_from_invariant(inv)):28s} elementary divisors {divisors_label(inv):34s} "
                      f"{'S_8 class ' + cls if cls else 'non-octad'}")
    print(f"all agree: {all_ok}")
    assert all_ok

    print("\nq = 4: all sixteen (l5, l3) in F_4^2  (F_4 = F_2[w]/(w^2+w+1), elements 0,1,2=w,3=w+1):")
    F = GF(2)
    O = Ore(F)
    for l5 in range(4):
        for l3 in range(4):
            P = kernel_polynomial(F, l5, l3)
            n = frobenius_order(O, P, 2)
            inv = frobenius_module(O, P, 2, n)
            cls = classify(inv, inv_to_classes)
            print(f"  (l5,l3)=({l5},{l3}): order {n:2d}, char poly {pstr(charpoly_from_invariant(inv)):28s} "
                  f"divisors {divisors_label(inv):34s} {'S_8 class ' + cls if cls else 'non-octad'}")


if __name__ == "__main__":
    self_test()
